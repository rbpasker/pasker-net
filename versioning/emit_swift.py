#!/usr/bin/env python3
"""Emit a self-contained Swift namespace mirroring ``canonical_version_client``.

Intended to be invoked from an Xcode "Run Script" build phase that lists
the output path as one of the phase's outputs, so the generated file is
picked up by the subsequent Sources compile phase.

The emitted file declares an ``enum`` (Swift's idiomatic namespace) with:

  * build-time constants baked in (``gitBranch``, ``gitCommit``,
    ``gitDirty``)
  * an ``appVersion`` getter that reads ``CFBundleShortVersionString``
    from the host app's ``Info.plist`` at runtime — single source of
    truth, same value the App Store / Apple sees
  * an ``os`` getter that uses ``ProcessInfo.operatingSystemVersion``
    everywhere (works on iOS / iPadOS / tvOS / watchOS / visionOS /
    macOS / Catalyst with zero platform-specific imports) and a
    compile-time ``#if os(…)`` for the platform name
  * ``build`` — ``<app>-<revNumber>`` clean; a dirty build appends
    ``[-<branch>]-dirty (<buildTime>)`` (a Zulu-time stamp). Mirrors the Python
    ``canonical_version_client`` (rev, no commit hash).
  * ``buildKind`` / ``buildSuffix`` / ``tagAppVersion`` — the build kind (``d`` /
    ``a`` / ``b`` / empty), its suffix (the same letter) and the tag-derived
    version, baked from the git tags (Apple's plist version can't hold a kind);
    ``build`` appends the suffix: ``0.9b-70``, ``0.10d-71``
  * ``full`` — ``<build> (<os>)``

Note: ``#if os(iOS)`` is true on iPad as well — Swift has no
``os(iPadOS)`` compile flag, so iPad will label as "iOS". If you need
to distinguish, override ``os`` in your target with a UIDevice-based
check.

Usage from an Xcode build phase (mirrors the existing BuildStamp pattern):

    python3 "${SRCROOT}/../../vendor/pasker-net/versioning/emit_swift.py" \\
        --repo-root "${SRCROOT}/../.." \\
        --out "${SRCROOT}/EdmundCapture/CanonicalVersion.swift"

Add the same ``--out`` path to the phase's ``outputPaths`` so Xcode tracks
it. Set ``alwaysOutOfDate = 1`` so it regenerates each build (the dirty
flag and commit can change between builds even when the script's args
don't).

Re-runs are idempotent: same git state + same args → byte-identical file
(so Xcode's incremental build sees no change to the source).
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

# Allow running as a script without installing the package.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from versioning.versioning import (  # noqa: E402
    _git, _is_dirty, _resolve_app_version, build_kind, build_number,
)


_TEMPLATE = '''\
// Auto-generated by versioning/emit_swift.py — do not edit by hand.
// Regenerated by the Xcode Run Script Phase on every build.
import Foundation

enum {type_name} {{
    static let gitBranch = "{git_branch}"
    static let gitCommit = "{git_commit}"
    static let gitDirty  = {git_dirty}

    /// `git rev-list --count HEAD` — the same monotonic integer baked into
    /// CFBundleVersion / CURRENT_PROJECT_VERSION at release.
    static let revNumber = {rev_number}

    /// Zulu (UTC) build time, baked **only for dirty builds** (empty otherwise,
    /// so a clean build regenerates byte-identically). A clean build's time is
    /// recoverable from its commit; a dirty build has no commit to point at.
    static let buildTime = "{build_time}"

    /// Build kind, from the git tags: "d" development (ahead of a release tag),
    /// "a" alpha, "b" beta, "" release. What a kind means to the app (update
    /// channel, audience) is the app's business — compare this, don't parse it.
    static let buildKind = "{build_kind}"

    /// The kind as a version suffix: "" release, "d" development, "a" alpha, "b"
    /// beta. Apple requires CFBundleShortVersionString to be digits and
    /// dots only, so this cannot live in the plist — it is baked here and appended
    /// in `build`.
    static let buildSuffix = "{build_suffix}"

    /// The app version the git tags imply for this build ("0.9b", "0.10", "0.8").
    /// Compare its release part with `appVersion` to catch a plist whose
    /// MARKETING_VERSION has drifted from the tags (`appVersionMatchesTags`).
    static let tagAppVersion = "{tag_app_version}"

    /// Trunk branch names whose name is omitted from `build`.
    static let mainBranches: Set<String> = [{main_branches}]

    /// CFBundleShortVersionString from the host app's Info.plist — the marketing
    /// version "X.x" (same value the App Store / Apple sees).
    static var appVersion: String {{
        (Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String) ?? "unknown"
    }}

    /// True when the plist's marketing version equals the release part of the
    /// tag-derived version (`0.9` for `0.9b`), ignoring a patch component.
    static var appVersionMatchesTags: Bool {{
        let tag = tagAppVersion.split(whereSeparator: {{ !"0123456789.".contains($0) }}).first.map(String.init) ?? tagAppVersion
        let a = appVersion.split(separator: ".").prefix(2).joined(separator: ".")
        let t = tag.split(separator: ".").prefix(2).joined(separator: ".")
        return a == t
    }}

    /// Clean: "<X.x><kind>-<revNumber>" — Apple's "X.x (revNumber)" with the
    /// build kind (if any) after the version, e.g. "0.9b-70" or "0.10d-71".
    /// Dirty: appends "-[<branch>-]dirty (<buildTime>)" (branch omitted on a
    /// trunk branch / detached HEAD).
    static var build: String {{
        var s = "\\(appVersion)\\(buildSuffix)-\\(revNumber)"
        if gitDirty {{
            if !gitBranch.isEmpty, gitBranch != "HEAD", !mainBranches.contains(gitBranch) {{
                s += "-\\(gitBranch)"
            }}
            s += "-dirty (\\(buildTime))"
        }}
        return s
    }}

    /// "<Platform>-<version>", e.g. "iOS-17.5" / "macOS-14.5".
    /// `ProcessInfo.operatingSystemVersion` works on every Apple platform;
    /// the platform name is a compile-time `#if os(...)` so no UIKit /
    /// WatchKit import is needed. Note: iPad reports as "iOS" because
    /// Swift has no `os(iPadOS)` flag.
    static var os: String {{
        let v = ProcessInfo.processInfo.operatingSystemVersion
        let ver = v.patchVersion == 0
            ? "\\(v.majorVersion).\\(v.minorVersion)"
            : "\\(v.majorVersion).\\(v.minorVersion).\\(v.patchVersion)"
        #if os(macOS)
        let name = "macOS"
        #elseif os(iOS)
        let name = "iOS"
        #elseif os(tvOS)
        let name = "tvOS"
        #elseif os(watchOS)
        let name = "watchOS"
        #elseif os(visionOS)
        let name = "visionOS"
        #else
        let name = "Apple"
        #endif
        return "\\(name)-\\(ver)"
    }}

    /// "<build> (<os>)"
    static var full: String {{ "\\(build) (\\(os))" }}
}}
'''


def _swift_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def emit(
    repo_root: str | None,
    type_name: str,
    main_branches: tuple[str, ...],
    component: str | None = None,
) -> str:
    cwd = repo_root or None
    # Raises GitError if the tag lookup times out (fails the build loudly, not NOVERSION).
    tag_version = _resolve_app_version(cwd, component)
    kind = build_kind(tag_version)
    suffix = kind
    branch = _git(["rev-parse", "--abbrev-ref", "HEAD"], cwd) or ""
    commit = _git(["rev-parse", "--short", "HEAD"], cwd) or "unknown"
    dirty = _is_dirty(cwd)
    rev = build_number(cwd)
    rev = rev if rev is not None else 0
    # Buildtime is baked ONLY for dirty builds; clean builds leave it empty so
    # the generated file is byte-identical across rebuilds (idempotent).
    build_time = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ") if dirty else ""
    return _TEMPLATE.format(
        type_name=type_name,
        git_branch=_swift_escape(branch),
        git_commit=_swift_escape(commit),
        git_dirty="true" if dirty else "false",
        rev_number=rev,
        build_time=_swift_escape(build_time),
        build_suffix=suffix,
        build_kind=kind,
        tag_app_version=_swift_escape(tag_version),
        main_branches=", ".join(f'"{_swift_escape(b)}"' for b in main_branches),
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--repo-root", default=None,
                    help="Path to the git repo. Defaults to cwd.")
    ap.add_argument("--out", required=True, type=Path,
                    help="Destination Swift file.")
    ap.add_argument("--type-name", default="CanonicalVersion",
                    help='Name of the emitted Swift enum (default: "CanonicalVersion")')
    ap.add_argument("--component", default=None, metavar="NAME",
                    help="Scope the tag lineage to `<NAME>-<X.x>` tags (the pre-release "
                         "stage and tag-derived version come from them).")
    ap.add_argument("--main-branch", action="append", default=None,
                    metavar="NAME",
                    help='Branch name to treat as trunk (omit infix). '
                         'May be passed multiple times. Defaults to "main" and "master".')
    args = ap.parse_args()

    main_branches = tuple(args.main_branch) if args.main_branch else ("main", "master")
    body = emit(args.repo_root, args.type_name, main_branches, args.component)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    # Only write if changed, to avoid invalidating Xcode's incremental build.
    if args.out.exists() and args.out.read_text() == body:
        return 0
    args.out.write_text(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
