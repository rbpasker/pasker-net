#!/usr/bin/env python3
"""Emit a self-contained Swift namespace mirroring ``canonical_version``.

Intended to be invoked from an Xcode "Run Script" build phase that lists
the output path as one of the phase's outputs, so the generated file is
picked up by the subsequent Sources compile phase.

The emitted file declares an ``enum`` (Swift's idiomatic namespace) with:

  * build-time constants baked in (``gitBranch``, ``gitCommit``,
    ``gitDirty``)
  * an ``appVersion`` getter that reads ``CFBundleShortVersionString``
    from the host app's ``Info.plist`` at runtime — single source of
    truth, same value the App Store / Apple sees
  * an ``os`` getter that uses ``ProcessInfo.operatingSystemVersion``
    everywhere (works on iOS / iPadOS / tvOS / watchOS / visionOS /
    macOS / Catalyst with zero platform-specific imports) and a
    compile-time ``#if os(…)`` for the platform name
  * ``build`` — ``<app>[-<branch>]-<commit>[-dirty]``
  * ``full`` — ``<build> (<os>)``

Note: ``#if os(iOS)`` is true on iPad as well — Swift has no
``os(iPadOS)`` compile flag, so iPad will label as "iOS". If you need
to distinguish, override ``os`` in your target with a UIDevice-based
check.

Usage from an Xcode build phase (mirrors the existing BuildStamp pattern):

    python3 "${SRCROOT}/../../vendor/pasker-net/versioning/emit_swift.py" \\
        --repo-root "${SRCROOT}/../.." \\
        --out "${SRCROOT}/EdmundCapture/CanonicalVersion.swift"

Add the same ``--out`` path to the phase's ``outputPaths`` so Xcode tracks
it. Set ``alwaysOutOfDate = 1`` so it regenerates each build (the dirty
flag and commit can change between builds even when the script's args
don't).

Re-runs are idempotent: same git state + same args → byte-identical file
(so Xcode's incremental build sees no change to the source).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Allow running as a script without installing the package.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from versioning.versioning import _git, _is_dirty  # noqa: E402


_TEMPLATE = '''\
// Auto-generated by versioning/emit_swift.py — do not edit by hand.
// Regenerated by the Xcode Run Script Phase on every build.
import Foundation

enum {type_name} {{
    static let gitBranch = "{git_branch}"
    static let gitCommit = "{git_commit}"
    static let gitDirty  = {git_dirty}

    /// Trunk branch names whose name is omitted from `build`.
    static let mainBranches: Set<String> = [{main_branches}]

    /// CFBundleShortVersionString from the host app's Info.plist.
    static var appVersion: String {{
        (Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String) ?? "unknown"
    }}

    /// "<app>[-<branch>]-<commit>[-dirty]"
    static var build: String {{
        var parts = [appVersion]
        if !gitBranch.isEmpty, gitBranch != "HEAD", !mainBranches.contains(gitBranch) {{
            parts.append(gitBranch)
        }}
        parts.append(gitCommit)
        if gitDirty {{ parts.append("dirty") }}
        return parts.joined(separator: "-")
    }}

    /// "<Platform>-<version>", e.g. "iOS-17.5" / "macOS-14.5".
    /// `ProcessInfo.operatingSystemVersion` works on every Apple platform;
    /// the platform name is a compile-time `#if os(...)` so no UIKit /
    /// WatchKit import is needed. Note: iPad reports as "iOS" because
    /// Swift has no `os(iPadOS)` flag.
    static var os: String {{
        let v = ProcessInfo.processInfo.operatingSystemVersion
        let ver = v.patchVersion == 0
            ? "\\(v.majorVersion).\\(v.minorVersion)"
            : "\\(v.majorVersion).\\(v.minorVersion).\\(v.patchVersion)"
        #if os(macOS)
        let name = "macOS"
        #elseif os(iOS)
        let name = "iOS"
        #elseif os(tvOS)
        let name = "tvOS"
        #elseif os(watchOS)
        let name = "watchOS"
        #elseif os(visionOS)
        let name = "visionOS"
        #else
        let name = "Apple"
        #endif
        return "\\(name)-\\(ver)"
    }}

    /// "<build> (<os>)"
    static var full: String {{ "\\(build) (\\(os))" }}
}}
'''


def _swift_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def emit(
    repo_root: str | None,
    type_name: str,
    main_branches: tuple[str, ...],
) -> str:
    cwd = repo_root or None
    branch = _git(["rev-parse", "--abbrev-ref", "HEAD"], cwd) or ""
    commit = _git(["rev-parse", "--short", "HEAD"], cwd) or "unknown"
    dirty = _is_dirty(cwd)
    return _TEMPLATE.format(
        type_name=type_name,
        git_branch=_swift_escape(branch),
        git_commit=_swift_escape(commit),
        git_dirty="true" if dirty else "false",
        main_branches=", ".join(f'"{_swift_escape(b)}"' for b in main_branches),
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--repo-root", default=None,
                    help="Path to the git repo. Defaults to cwd.")
    ap.add_argument("--out", required=True, type=Path,
                    help="Destination Swift file.")
    ap.add_argument("--type-name", default="CanonicalVersion",
                    help='Name of the emitted Swift enum (default: "CanonicalVersion")')
    ap.add_argument("--main-branch", action="append", default=None,
                    metavar="NAME",
                    help='Branch name to treat as trunk (omit infix). '
                         'May be passed multiple times. Defaults to "main" and "master".')
    args = ap.parse_args()

    main_branches = tuple(args.main_branch) if args.main_branch else ("main", "master")
    body = emit(args.repo_root, args.type_name, main_branches)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    # Only write if changed, to avoid invalidating Xcode's incremental build.
    if args.out.exists() and args.out.read_text() == body:
        return 0
    args.out.write_text(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
